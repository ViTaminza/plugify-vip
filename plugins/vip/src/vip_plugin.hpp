namespace vip {

inline constexpr int32_t kMaxSlots = 64;
// The once-per-second loop of the original (reconcile + expiry), the plgdb Poll pump and their
// fixed steps live in tick_accumulator.hpp: no s2sdk timer is created for either.
// A vip_users read that did not answer is retried with a growing delay: while the database is
// down, every unloaded slot would otherwise queue another SELECT the moment the previous one
// failed, and the finishing queue would all fire VIP_OnClientLoaded at once.
inline constexpr std::chrono::seconds kLoadRetryAfter{10};
inline constexpr std::chrono::seconds kLoadRetryMax{120};
// A core that could not be created at plugin start (the database was not accepting connections
// yet) is retried from the update pump with the same kind of backoff.
inline constexpr std::chrono::seconds kCoreRetryAfter{10};
inline constexpr std::chrono::seconds kCoreRetryMax{60};

// One registered VIP feature (g_VipFunctions of the original, keyed by feature name).
struct Feature {
	int value_type = kValueNull; // VIP_ValueType
	int feature_type = 0;        // VIP_FeatureType: 0 = TOGGLABLE, 1 = SELECTABLE, 2 = HIDE
	ItemSelectableDelegate select = nullptr;
	ItemTogglableDelegate toggle = nullptr;
	ItemDisplayDelegate display = nullptr;
};

// A VIP_OnPlayerSpawn callback that is one frame late (the original's NextFrame): it keeps the
// identity of the slot when the event arrived and is revalidated before it runs.
struct PendingSpawn {
	int32_t slot = -1;
	uint64_t steamid = 0;
	int32_t controller = 0;
	// The one-frame delay of the original's NextFrame(), counted down by the update delta.
	std::chrono::milliseconds remaining{0};
};

class VipPlugin final : public plg::Plugin {
public:
	// --- lifecycle -------------------------------------------------------------------
	plg::PluginResult OnPluginStart() override;
	plg::PluginResult OnPluginUpdate(std::chrono::milliseconds dt) override;
	plg::PluginResult OnPluginEnd() override;

	// --- engine side (game thread) -----------------------------------------------------
	// s2sdk OnClientAuthenticated + the once-per-second reconcile (the event may not fire).
	void HandleClientAuthenticated(int32_t slot, uint64_t steamid);
	// s2sdk OnClientPutInServer: the welcome message of the original when the record is known.
	void HandleClientPutInServer(int32_t slot);
	void HandleClientDisconnect(int32_t slot);
	// player_spawn: one update later, for a living non-bot player (the handle dance of the
	// original). |event| is s2sdk's IGameEvent pointer; the slot is read with GetEventPlayerSlot.
	void HandlePlayerSpawn(void* event);
	// round_prestart: recompute g_bPistolRound.
	void HandleRoundPreStart();
	// The s2sdk map listeners: OnMapStart opens the gate state, OnMapEnd closes it and only
	// clears state (PITFALLS B2).
	void HandleMapStart();
	void HandleMapEnd();
	// Run once with the core ready: deletes the expired rows of this server (OnStartupServer).
	void OnStartupServer();
	// Once per second: reconcile slots + expire VIPs (the GameFrame loop of the original).
	void OnSecondTick();
	// The permissions OnUserLoaded listener (permissions::LoadUser) - the cookie store is ready.
	void HandleUserLoaded(uint64_t steamid64);

	// --- vip_core hooks ------------------------------------------------------------------
	void HandleLoaded(int32_t slot, const VipLoadOutcome& outcome, LoadPurpose purpose);
	void HandleCoreError(std::string_view message);

	// --- configuration ---------------------------------------------------------------------
	bool LoadGroups();   // groups.ini (the g_VipGroups of the original)
	bool LoadPhrases();  // vip.phrases.txt (the g_vecPhrases of the original)
	// The vip_reload command: LoadVips() again. True on success (the caller prints the message).
	bool ReloadVipData() { return LoadGroups(); }
	const Config& Cfg() const { return m_config; }
	bool IsReady() const { return m_ready; }        // VIP_IsVIPLoaded
	bool CoreReady() const { return m_core != nullptr; }
	// The g_vecPhrases lookup of the original: an unknown key prints as an empty string (the
	// modules rely on the empty value).
	std::string Phrase(std::string_view key) const;
	const std::string& Language() const { return m_language; }
	const plgdb::Config& DatabaseConfig() const { return m_db_config; }

	// --- slot data ----------------------------------------------------------------------------
	uint64_t SteamIdOf(int32_t slot) const;
	uint32_t AccountIdOf(int32_t slot) const;
	// A connected, authenticated, in-game, non-bot, non-SourceTV player with a validated
	// controller entity, on a running map (PITFALLS B1/B2/C2).
	bool IsSlotHuman(int32_t slot) const;
	// A connected, authenticated, non-bot client, without the in-game/controller requirements:
	// the reconcile and expiry loop of the original worked on this layer.
	bool IsSlotConnectedHuman(int32_t slot) const;
	std::string PlayerName(int32_t slot) const;
	// The engine steamid of a connected slot (0 when there is no client): the live half of the
	// SteamID64 + controller-handle revalidation of every deferred action.
	uint64_t ClientSteamIdOf(int32_t slot) const;
	// The identity vip_core works with; name is the tracked/engine name.
	VipIdentity IdentityOf(int32_t slot) const;
	// The identity built from the tracked slot state only - no client call (map-end safe).
	VipIdentity TrackedIdentityOf(int32_t slot) const;
	// The validated controller entity handle of the slot (0 when it has none). C1: 0 and -1 are
	// invalid, any other value - negative included - is checked with s2sdk::IsValidEntHandle.
	int32_t ControllerHandleOf(int32_t slot) const;

	// --- API surface (used by the exports and the menu/command code) ---------------------------
	bool IsClientVip(int32_t slot);
	int32_t AccessTime(int32_t slot);
	bool SetAccessTime(int32_t slot, int32_t time, bool in_db);
	std::string GroupName(int32_t slot);
	bool SetGroup(int32_t slot, const std::string& group, bool in_db);
	bool GiveVip(int32_t slot, int32_t time, const std::string& group, bool add_to_db);
	bool RemoveVip(int32_t slot, bool notify, bool in_db);
	bool IsValidGroup(const std::string& group) const;

	int32_t FeatureInt(int32_t slot, const char* feature);
	bool FeatureBool(int32_t slot, const char* feature);
	float FeatureFloat(int32_t slot, const char* feature);
	std::string FeatureString(int32_t slot, const char* feature);
	void RegisterFeature(const plg::string& feature, int value_type, int feature_type, ItemSelectableDelegate select,
						 ItemTogglableDelegate toggle, ItemDisplayDelegate display);
	// The resolved feature table of a slot (GetGroupKV of the original), nullptr when the player
	// is not a VIP / has no group / the group has no features.
	const GroupFeatures* GroupFeaturesForSlot(int32_t slot);
	// vip_status: one line per connected slot with every check GroupFeaturesForSlot makes, in
	// order (empty for a free slot). Diagnostics only.
	std::string DiagnoseSlot(int32_t slot);

	// Cookies: '<group>.<name>' in the official permissions plugin (the ICookiesApi of the
	// original, same keys).
	bool SetCookie(int32_t slot, const std::string& name, const std::string& data);
	std::string GetCookie(int32_t slot, const std::string& name);
	// The permission cookie store of a slot is available (permissions plugin loaded).
	bool CookiesAvailable() const;

	void PrintToCenter(int32_t slot, const std::string& msg);
	void OpenMenu(int32_t slot);
	void ShowMenu(int32_t slot, bool reopen);
	// menus.cpp: the build+display half of ShowMenu; only ProcessMenuWork calls it, outside the
	// menu manager's lock and after the SteamID64/controller revalidation of the queued action.
	void ShowMenuNow(int32_t slot);
	// The callback of the VIP menu (VIPCallback of the original); runs outside the menu handler.
	void HandleMenuCallback(const char* back, const char* front, int item, int slot);

	// --- game state --------------------------------------------------------------------------------
	bool PistolRound() const;
	bool WarmupPeriod();
	int32_t TotalRounds();
	void SetPistolRound(bool value) { m_pistol_round = value; }

	// --- command support (commands.cpp) -------------------------------------------------------------
	// The name/account-id/slot search of mm_reload_vip, vip_remove and vip_give. require_pawn
	// keeps the extra "the player must have a pawn" condition of vip_give.
	int FindPlayerSlot(const std::string& token, bool require_pawn = false) const;
	// The mm_reload_vip body: drops the record and re-reads the row.
	void ReloadClientVip(int32_t slot);
	// The offline branch of vip_give: INSERT a vip_users row for an account id typed on the
	// command line (name 'none', like the original).
	void GiveOfflineVip(const std::string& account_id_text, int32_t seconds, const std::string& group);
	// The permissions plugin id (0 when the plugify binding is unavailable).
	int64_t PluginId() const;

	// --- callback registries (the IVIPApi registration methods) --------------------------------------
	std::vector<ReadyDelegate>& ReadyListeners() { return m_on_ready; }
	std::vector<ClientLoadedOrDisconnectDelegate>& ClientLoadedListeners() { return m_on_client_loaded; }
	std::vector<ClientLoadedOrDisconnectDelegate>& ClientDisconnectListeners() { return m_on_client_disconnect; }
	std::vector<SpawnDelegate>& PlayerSpawnListeners() { return m_on_player_spawn; }
	std::vector<VipRemoveDelegate>& VipRemovedListeners() { return m_on_vip_removed; }
	std::vector<VipAddDelegate>& VipAddedListeners() { return m_on_vip_added; }

	void FireReady();
	void FireClientLoaded(int32_t slot, bool is_vip);
	void FireClientDisconnect(int32_t slot, bool is_vip);
	void FirePlayerSpawn(int32_t slot, int32_t team, bool is_vip);
	void FireVipRemoved(int32_t slot, int32_t reason);
	void FireVipAdded(int32_t slot);

	// --- spawn queue (VIP_OnPlayerSpawn) ------------------------------------------------------------
	void QueuePlayerSpawn(int32_t slot, uint64_t steamid, int32_t controller);
	void ProcessPendingSpawns(std::chrono::milliseconds dt);

private:
	struct SlotState {
		uint64_t steamid = 0;
		uint32_t account_id = 0;
		bool requested = false;           // a load was started for this connection
		bool loading = false;             // ... and its SELECT is still outstanding
		bool loaded = false;              // the vip_users read answered
		bool client_loaded_fired = false; // VIP_OnClientLoaded fired from the database path
		bool user_loaded_seen = false;    // the permissions user was loaded before the row
		bool user_loaded_fired = false;   // ... and the second (cookie) event was fired
		std::string name;
		std::chrono::seconds retry_delay{kLoadRetryAfter}; // grows while the reads keep failing
		std::chrono::steady_clock::time_point requested_at{};
	};

	// --- startup steps ---------------------------------------------------------------------
	bool CreateCore();  // database + core + groups (the part of EnsureCore that can be retried)
	bool EnsureCore();  // ... plus the blocking CREATE TABLE (startup only)
	// The startup retry: a core that failed at OnPluginStart is created by the update pump, with
	// the CREATE TABLE on the plgdb worker (never on the game thread) and a growing backoff.
	void RetryCore();
	void ScheduleCoreRetry();
	void DropFailedCore();     // after a failed CREATE TABLE: drop the objects (update pump only)
	void PromoteRetriedCore(); // async CREATE TABLE answered OK: ready + ready listeners
	bool LoadDatabaseConfig();
	void LoadPhrasesLanguage();
	void RegisterMapListeners();
	void UnregisterMapListeners();
	void RegisterClientListeners();
	void UnregisterClientListeners();
	void RegisterEvents();
	void UnregisterEvents();
	void RegisterCommandsAndEvents();
	// The permissions plugin is an optional dependency: its binding slots may still be empty when
	// this plugin starts (or filled later), so availability is checked lazily on every use and
	// the OnUserLoaded listener is registered as soon as the complete pair appears.
	void EnsurePermissionsListener();
	void ReleasePermissionsListener();

	// --- config path resolution (the previous wrapper's first-existing-file rule) -------------------
	// The first existing candidate wins (raw server path, then <configs>/<plugin>/, translations
	// and data); a malformed file is reported and the caller keeps its previous state.
	std::string ResolveConfigPath(std::string_view path) const;
	std::string ResolveTranslationsPath(std::string_view path) const;
	std::string ResolveDataPath(std::string_view path) const;

	// --- per-second work ---------------------------------------------------------------------
	void ReconcileSlots();
	void ExpireLoop();

	// --- helpers -------------------------------------------------------------------------------
	void Welcome(int32_t slot, const std::string& group, int64_t expires) const;
	void NotifyExpired(int32_t slot) const;
	void ClearSlot(int32_t slot);
	void ResetState();
	// Reads a gamerules field of the game schema (CCSGameRules); |def| when it is not available.
	// |cache| holds the schema offset of that field (resolved with the map gate open only, C8).
	int GameRulesInt(const char* field, int def, int& cache) const;
	bool GameRulesBool(const char* field, bool def, int& cache) const;
	// A schema offset resolved only with a live map (C8); only successful results are cached.
	int SchemaOffset(const char* className, const char* field, int& cache) const;
	// The controller's m_iTeamNum (1 byte) read with the validated controller handle.
	int32_t TeamOfSlot(int32_t slot) const;
	bool SchemaOffsetReady(int offset) const { return offset >= 0; }

	Config m_config;
	plgdb::Config m_db_config;
	std::unique_ptr<plgdb::Database> m_db;
	std::unique_ptr<VipCore> m_core;
	kv::PhraseMap m_phrases;
	std::string m_language;
	bool m_running = false;
	bool m_ready = false;
	bool m_startup_pending = false;
	bool m_permissions_listener_registered = false;
	bool m_permissions_warned = false;
	bool m_auth_listener = false;
	bool m_put_in_server_listener = false;
	bool m_disconnect_listener = false;
	bool m_spawn_event_hooked = false;
	bool m_prestart_event_hooked = false;
	bool m_map_listeners_registered = false;
	// The startup retry of a core whose database was not available at OnPluginStart.
	bool m_core_retry_wait = false;  // OnPluginStart failed: the update pump retries the core
	bool m_core_starting = false;    // the retry's CREATE TABLE is on the plgdb worker
	bool m_core_promote = false;     // ... and answered OK; promoted on the next update
	bool m_core_drop = false;        // ... and failed; the objects are dropped on the next update
	std::chrono::steady_clock::time_point m_core_retry_at{};
	std::chrono::seconds m_core_retry_delay{kCoreRetryAfter};

	std::map<std::string, Feature, std::less<>> m_features; // g_VipFunctions
	std::array<SlotState, kMaxSlots> m_slots{};
	std::vector<PendingSpawn> m_pending_spawns;
	bool m_pistol_round = true; // provisional: unknown until the next real round_prestart
	TickAccumulator m_second_tick{kSecondTickInterval};
	TickAccumulator m_database_tick{kDatabasePollInterval};
	// The schema offsets of the game rules fields (resolved on first use, -1 when unknown).
	mutable int m_offset_warmup = -1;
	mutable int m_offset_switching = -1;
	mutable int m_offset_overtime = -1;
	mutable int m_offset_restart = -1;
	mutable int m_offset_total_rounds = -1;
	mutable int m_offset_team = -1;

	std::vector<ReadyDelegate> m_on_ready;
	std::vector<ClientLoadedOrDisconnectDelegate> m_on_client_loaded;
	std::vector<ClientLoadedOrDisconnectDelegate> m_on_client_disconnect;
	std::vector<SpawnDelegate> m_on_player_spawn;
	std::vector<VipRemoveDelegate> m_on_vip_removed;
	std::vector<VipAddDelegate> m_on_vip_added;
};

extern VipPlugin g_vipPlugin;

// --- map gate (B1/B2, plugin.cpp) ----------------------------------------------------------------
// Whether s2sdk client/entity/schema calls are safe right now. False before the first map, in the
// OnMapEnd..OnMapStart window and after OnPluginEnd.
bool IsGameReady();
// s2sdk::GetCurrentMap() names a real map (non-empty and not "<empty>"); null-safe and safe to ask
// before the first map (it only null-checks gpGlobals).
bool GameMapLoaded();

// --- shared helpers (plugin.cpp) ----------------------------------------------------------------
// Logs through plg::Log (never throws, no-op when the module did not set the slot).
void LogMessage(std::string_view message, plg::Severity severity);
void LogInfo(std::string_view message);
void LogWarn(std::string_view message);
void LogError(std::string_view message);
std::string FormatTimestamp(int64_t timestamp); // "YYYY-MM-DD HH:MM:SS" of an absolute timestamp
std::string CookieToString(const plg::any& value); // the permissions cookie value as text
// One chat line, colourised and gated on the map/slot (never touches a client while the gate is
// shut or the slot is empty).
void ChatLine(int32_t slot, std::string_view text);
// A server-console line: colour tags stripped, printed through s2sdk::PrintToServer when it is
// available and plg::Log otherwise.
void ServerConsole(std::string_view text);

// --- commands.cpp ---------------------------------------------------------------------------------
// Registers mm_vip/sm_vip/vip, vip_status, vip_reload, mm_reload_vip, vip_remove and vip_give.
void RegisterCommands();
void RemoveCommands();

// --- menus.cpp --------------------------------------------------------------------------------------
// The VIP menu of a player (ShowVIPMenu(..., true)) and its lifecycle.
void ShowVipMenu(int32_t slot);
// OnPluginStart: checks the complete menu binding set and burns s2sdk menu id 0. Returns whether
// the menu subsystem is usable.
bool SetupMenus();
// OnPluginUpdate: drains the deferred show/close/destroy queue and retries parked menus.
void ProcessMenuWork();
// OnMapEnd: ends every display with Disconnect, rechecks, destroys with the no-op-close fallback.
void TeardownMenusOnMapEnd();
// OnPluginEnd: the same for every menu this plugin still owns; reports A7_UNRESOLVED if any
// cannot be released.
void TeardownMenusOnUnload();
// Whether the complete menu lifecycle binding set was available at start.
bool MenusAvailable();

} // namespace vip
