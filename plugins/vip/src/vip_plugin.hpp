#pragma once
// vip — engine side of the "vip" plugin: the ported cs2-vip core (groups.ini, the vip_users loads
// and the once-per-second expiry loop, the VIP menu, the commands) on pure s2sdk + plgdb + the
// optional permissions plugin (the cookie store).
//
// Everything here runs on the game thread: the plugify update pump (OnPluginUpdate), s2sdk
// listeners, console/chat callbacks, deferred menu actions and the update-driven tick. No locking
// is needed; nothing blocks on the database except CreateSchema() at plugin start.
//
// No pisexcompat and no wrapper library (docs/PLUGIN_STANDARD.md §7). The safety rules of
// handoff/weaponskins/PITFALLS.md live in this file and its neighbours:
//   * B1/B2 map gate: the OnMapStart/OnMapEnd listeners are registered (with the full
//     register+unregister pair) in OnPluginStart; readiness is granted by OnMapStart or by the
//     first OnPluginUpdate of a plugin loaded into a running map - and that mid-map latch only
//     fires when all four map-listener bindings are registered, no OnMapEnd was seen since
//     OnPluginStart, and s2sdk::GetCurrentMap() names a real map (non-empty and not "<empty>").
//     OnMapEnd only clears state. No client, entity or schema call is made while the gate is shut.
//   * A1/A7: OnPluginStart never returns Failed; every registration is checked for its complete
//     add+remove pair before it happens, and OnPluginEnd removes everything symmetrically.
//   * C1/C2: entity handles are signed int32 values - only 0 and -1 are invalid, a negative
//     handle may be real (serial bit 31) and is checked with s2sdk::IsValidEntHandle; a slot is a
//     connected, in-game, non-SourceTV, non-bot client with a validated controller entity.
//   * C8: schema offsets are resolved only with the map gate open and only successful results
//     (>= 0) are cached.
//   * C9/B4: there is no s2sdk timer. The spawn delay of VIP_OnPlayerSpawn, the once-per-second
//     reconcile/expiry loop and even the plgdb Poll() pump are accumulators driven by
//     OnPluginUpdate(dt); every deferred action revalidates SteamID64 + controller handle.
//
// Layout of the glue:
//   plugin.cpp    lifecycle, config/phrase/database loading, s2sdk listeners, the map gate, the
//                 update-driven tick, the vip_core hooks, the messages of the original and the
//                 34 exported methods (IVIPApi)
//   commands.cpp  vip_reload, mm_reload_vip, vip_remove, vip_give (+ the !vip / mm_vip / sm_vip
//                 menu command and vip_status diagnostics)
//   menus.cpp     the VIP menu (ShowVIPMenu / VIPCallback of the original) on native s2sdk menus
//   kv1.hpp       the read-only Valve KeyValues reader (groups.ini, databases.cfg, phrases)
//   text.hpp      colour tags, phrase-language normalisation, printf formatting
//   tick_accumulator.hpp  the fixed-step accumulator that replaces every timer
//   menu_type.hpp the exact ResolveS2sdkMenuTypeName table of the old wrapper
//
// The exported methods use the callback typedefs of the generated headers (<vip/vip.hpp>,
// generated by bin/plugify-gen) - the same types the consumer headers hand to modules, so the
// boundary is checked by the compiler. The generated *binding slots* (__vip_*) stay null in this
// plugin: it implements the API, it never calls it.

